"""Raise the frequency of words common in everyday sentences.

Usage: find-boosts.py LANG WORDLIST.combined.gz SUPPLEMENT TATOEBA.tsv RULES_DIR OUT
                      [--min-count N] [--margin STEPS] [--weight W]

The AOSP frequencies come largely from encyclopedic text: in Italian
`pensò` (past historic) outranks `penso`, `romani` outranks `domani`, and
`voglio` is rare. TATOEBA.tsv (count-words.py counts of the Tatoeba
sentences, CC BY 2.0 FR) is everyday language. For each word in the
wordlist or the supplement, its Tatoeba rate is mapped to the AOSP 0..255
scale with a least-squares fit; where that is at least --margin steps
higher, the frequency is raised towards it (--weight 1: all the way).
Frequencies are never lowered. OUT lists `word<TAB>f<TAB>evidence`;
build-dict.py reads it. Names in RULES_DIR/supplement.stop are skipped.
"""

import argparse
import gzip
import math
import sys


def read_list(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return [l.split("#", 1)[0].strip() for l in fh if l.split("#", 1)[0].strip()]
    except FileNotFoundError:
        return []


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("lang")
    ap.add_argument("wordlist")
    ap.add_argument("supplement")
    ap.add_argument("tatoeba")
    ap.add_argument("rules_dir")
    ap.add_argument("out")
    ap.add_argument("--min-count", type=int, default=5)
    ap.add_argument("--margin", type=int, default=3)
    ap.add_argument("--weight", type=float, default=1.0)
    args = ap.parse_args()

    words = {}
    with gzip.open(args.wordlist, "rt", encoding="utf-8") as fh:
        for line in fh:
            if line.startswith(" word="):
                fields = dict(kv.split("=", 1) for kv in line.strip().split(","))
                if fields.get("not_a_word") == "true" or int(fields["f"]) == 0:
                    continue
                words[fields["word"]] = max(int(fields["f"]), words.get(fields["word"], 0))
    for line in read_list(args.supplement):
        w, f = line.split("\t")[:2]
        words.setdefault(w, int(f))
    by_lower = {}
    for w in words:
        by_lower.setdefault(w.lower(), []).append(w)
    stop = {w.lower() for w in read_list(f"{args.rules_dir}/supplement.stop")}

    counts = {}
    with open(args.tatoeba, encoding="utf-8") as fh:
        for line in fh:
            w, c, cased = line.rstrip("\n").split("\t")[:3]
            counts[w] = (int(c), cased)
    total = sum(c for c, _ in counts.values())

    def rate(c):
        return c / total * 1e6

    # Fit f = a + b ln(rate) over words in both.
    xs, ys = [], []
    for k, forms in by_lower.items():
        if k in counts and counts[k][0] >= args.min_count:
            xs.append(math.log(rate(counts[k][0])))
            ys.append(max(words[w] for w in forms))
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    a = my - b * mx

    out = []
    for k, (c, cased) in counts.items():
        if c < args.min_count or k not in by_lower or k in stop:
            continue
        # The spelling the corpus uses inside sentences, if the list has it.
        forms = by_lower[k]
        w = cased if cased in forms else (k if k in forms else max(forms, key=lambda x: words[x]))
        target = min(255, round(a + b * math.log(rate(c))))
        if target - words[w] >= args.margin:
            f = round(words[w] + args.weight * (target - words[w]))
            out.append((w, f, f"f {words[w]} tatoeba {c}"))

    out.sort(key=lambda x: (-x[1], x[0]))
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("# SPDX-FileCopyrightText: Tatoeba contributors\n"
                 "# SPDX-License-Identifier: LicenseRef-CC-BY-2.0-FR\n"
                 "# Generated by tools/data/find-boosts.py from Tatoeba word counts (CC BY 2.0 FR);\n"
                 "# see THIRD-PARTY.md. Review changes.\n"
                 f"# Fit: f = {a:.1f} + {b:.2f} ln(rate per million), {n} words; weight {args.weight}.\n"
                 "# word\tf\tevidence (old f, Tatoeba count)\n")
        for w, f, ev in out:
            fh.write(f"{w}\t{f}\t{ev}\n")
    print(f"{args.lang}: {len(out)} words raised; fit f = {a:.1f} + {b:.2f} ln(rate)", file=sys.stderr)


if __name__ == "__main__":
    main()
